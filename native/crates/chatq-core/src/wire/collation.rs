//! What `-cne` lets by when [Open-ChatqSealed](src/phone-down.ps1) compares
//! a message's prefix. PowerShell compares two strings by the invariant
//! culture's collation (CompareOptions None), not code unit by code unit: a
//! character the collation gives no weight passes unseen wherever it
//! stands, and pwsh 7 takes another script's digit for the ASCII one. Which
//! characters those are differs by edition: Windows PowerShell 5.1 collates
//! with Windows' NLS, pwsh 7 with ICU.
//!
//! The tables are a scan of every code point, put before, inside and after
//! `chatq1` (the three gave the same set) and in place of each character of
//! `chatq1`, `chatq3c` and `chatq2p`, compared with CompareInfo.Compare under
//! both PowerShells (Windows 11 22631, pwsh 7.6). wire.json pins samples of
//! each. 5.1 also ignores a lone surrogate, which no Rust string holds.
//! Deferred: DEFERRED.md "Unicode tables scanned on one PC"

use crate::time::Flavour;
use std::cmp::Ordering;

/// Whether `fl`'s PowerShell gives `c` no weight at all when it compares.
pub(super) fn ignorable(c: char, fl: Flavour) -> bool {
    let table = match fl {
        Flavour::Desktop => DESKTOP_IGNORABLE,
        Flavour::Core => CORE_IGNORABLE,
    };
    let c = u32::from(c);
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                Ordering::Less
            } else if lo > c {
                Ordering::Greater
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

/// Whether `fl`'s PowerShell takes `c` for the ASCII digit `d`, of the two
/// the inbound prefixes hold: on pwsh 7 another script's 1 or 3 (Arabic-Indic,
/// Devanagari, Osmanya and the rest; not fullwidth, superscript or
/// mathematical), on 5.1 none.
pub(super) fn same_digit(c: char, d: char, fl: Flavour) -> bool {
    let table = match (fl, d) {
        (Flavour::Core, '1') => CORE_ONE,
        (Flavour::Core, '3') => CORE_THREE,
        _ => return false,
    };
    table.binary_search(&u32::from(c)).is_ok()
}

