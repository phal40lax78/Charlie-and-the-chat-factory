//! [ConvertTo-ChatqArgLine](src/queue.ps1) and
//! [Get-ChatqCmdArgRefusal](src/queue.ps1): the Windows command-line rules,
//! backslashes special only before a quote, and for a `.cmd` or `.bat`, which
//! cmd.exe reads first, `& | < > ^ ( )` quoted as well and what cmd cannot
//! carry refused. chatqd builds its own launches with [arg_line]; a run's CLI
//! gets [arg_line_for], from M5, the first milestone that starts one. Vector:
//! native/vectors/argline.json.

use crate::time::Flavour;

/// One argument line from a list, quoting only what needs it.
pub fn arg_line(args: &[String]) -> String {
    args.iter().map(|a| quote(a)).collect::<Vec<_>>().join(" ")
}

fn quote(a: &str) -> String {
    if a.is_empty() {
        return "\"\"".into();
    }
    // the exe branch's special set, '[\s"]'
    if !a.chars().any(|c| c.is_whitespace() || c == '"') {
        return a.into();
    }
    wrap(a)
}

/// `a` in quotes: a quote escaped, and the backslashes before it or before
/// the closing quote doubled.
fn wrap(a: &str) -> String {
    let mut s = String::with_capacity(a.len() + 2);
    s.push('"');
    let mut bs = 0;
    for ch in a.chars() {
        if ch == '\\' {
            bs += 1;
            continue;
        }
        if ch == '"' {
            s.push_str(&"\\".repeat(bs * 2 + 1));
            s.push('"');
        } else {
            s.push_str(&"\\".repeat(bs));
            s.push(ch);
        }
        bs = 0;
    }
    s.push_str(&"\\".repeat(bs * 2));
    s.push('"');
    s
}

/// [Test-ChatqCmdExe](src/queue.ps1): an executable Windows runs through
/// cmd.exe, a `.cmd` or `.bat` in any case. It is `-match '\.(cmd|bat)$'`,
/// whose `$` also matches before a final `\n`, so `claude.cmd` and a newline
/// is one too.
pub fn is_cmd_exe(exe: &str) -> bool {
    let e = exe.strip_suffix('\n').unwrap_or(exe).as_bytes();
    e.len() >= 4 && {
        let tail = &e[e.len() - 4..];
        tail.eq_ignore_ascii_case(b".cmd") || tail.eq_ignore_ascii_case(b".bat")
    }
}

/// [Get-ChatqCmdArgRefusal](src/queue.ps1): why `args` cannot go to `exe`,
/// or None. Only a `.cmd` or `.bat` refuses anything: the first argument
/// holding a quote, a `%name%` (two `%` with something between) or a line
/// break, named with its first 60 UTF-16 code units and an ellipsis, each run
/// of line breaks a space. The text is code units because PowerShell cuts
/// through a surrogate pair when one is there, leaving half of it.
pub fn cmd_arg_refusal(exe: &str, args: &[String]) -> Option<Vec<u16>> {
    if !is_cmd_exe(exe) {
        return None;
    }
    let a = args
        .iter()
        .find(|a| a.contains(['"', '\r', '\n']) || percent_name(a))?;
    let what = if a.contains('"') {
        "a quote"
    } else if percent_name(a) {
        "a %name%"
    } else {
        "a line break"
    };
    let mut shown: Vec<u16> = a.encode_utf16().collect();
    if shown.len() > 60 {
        shown.truncate(60);
        shown.push(0x2026);
    }
    let mut out: Vec<u16> = format!(
        "{} runs through cmd.exe, which cannot be handed {what} - not sent: ",
        leaf(exe)
    )
    .encode_utf16()
    .collect();
    // -replace '[\r\n]+', ' '
    let mut gap = false;
    for u in shown {
        let brk = u == 0x0D || u == 0x0A;
        if !brk {
            out.push(u);
        } else if !gap {
            out.push(0x20);
        }
        gap = brk;
    }
    Some(out)
}

/// `-match '%[^%]+%'`
fn percent_name(a: &str) -> bool {
    let at: Vec<usize> = a.match_indices('%').map(|(i, _)| i).collect();
    at.windows(2).any(|w| w[1] > w[0] + 1)
}

/// `Split-Path $Exe -Leaf` for a `.cmd` or `.bat`: what follows the last `\`
/// or `/`, or a path with neither without its `C:`.
fn leaf(exe: &str) -> &str {
    match exe.rfind(['\\', '/']) {
        Some(i) => &exe[i + 1..],
        None => match exe.as_bytes() {
            [d, b':', ..] if d.is_ascii_alphabetic() => &exe[2..],
            _ => exe,
        },
    }
}

/// [ConvertTo-ChatqArgLine](src/queue.ps1): `args` as one line for `exe`,
/// or the refusal it throws ([cmd_arg_refusal]). For a `.cmd` or `.bat` an
/// argument holding `& | < > ^ ( )` is quoted too. An argument PowerShell's
/// `-eq ''` takes for empty goes as `""`, its text lost: a culture compare,
/// so one made only of characters that compare ignores, a soft hyphen say,
/// and which those are depends on `fl`'s PowerShell.
pub fn arg_line_for(args: &[String], exe: &str, fl: Flavour) -> Result<String, Vec<u16>> {
    if let Some(no) = cmd_arg_refusal(exe, args) {
        return Err(no);
    }
    let cmd = is_cmd_exe(exe);
    let special = |c: char| {
        c.is_whitespace()
            || c == '"'
            || (cmd && matches!(c, '&' | '|' | '<' | '>' | '^' | '(' | ')'))
    };
    Ok(args
        .iter()
        .map(|a| {
            if ps_empty(a, fl) {
                "\"\"".to_string()
            } else if a.chars().any(special) {
                wrap(a)
            } else {
                a.clone()
            }
        })
        .collect::<Vec<_>>()
        .join(" "))
}

/// The `--name` [Invoke-ChatqRun](src/queue.ps1) gives a fresh chat whose
/// CLI is a `.cmd` or `.bat`, from its title: each of `" % ! & | < > ^` a
/// space, each run of white space one space, the ends trimmed.
pub fn cmd_title(title: &str) -> String {
    let mut out = String::with_capacity(title.len());
    let mut gap = false;
    for c in title.chars() {
        let c = if matches!(c, '"' | '%' | '!' | '&' | '|' | '<' | '>' | '^') {
            ' '
        } else {
            c
        };
        if c.is_whitespace() {
            if !gap {
                out.push(' ');
            }
            gap = true;
        } else {
            out.push(c);
            gap = false;
        }
    }
    out.trim().to_string()
}

/// `$a -eq ''`: InvariantCulture, IgnoreCase, so true as well for a string
/// of only characters the compare gives no weight.
fn ps_empty(a: &str, fl: Flavour) -> bool {
    let t = match fl {
        Flavour::Desktop => IGNORABLE_DESKTOP,
        Flavour::Core => IGNORABLE_CORE,
    };
    a.chars().all(|c| {
        let c = c as u32;
        t.as_chunks::<2>().0.iter().any(|&[s, e]| s <= c && c <= e)
    })
}

